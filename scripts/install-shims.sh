#!/usr/bin/env bash
# Generate PATH shims that route selected commands through rtk.
#
# WHY A SHIM AT ALL
# Claude Code rewrites `git status` into `rtk git status` from a PreToolUse
# hook. Hermes has no equivalent interception point, so the only place left to
# stand is PATH: put a directory of wrappers ahead of /usr/bin and the agent
# gets filtered output whether or not it remembers to ask for it.
#
# WHAT THAT COSTS
# A shim reshapes output for *every* process in the container, not just the
# agent's shell -- Hermes' own internals, s6 init scripts, anything that parses
# what a command prints. That is the risk this file is built to contain:
#
#   * Two levels. `safe` (default) only shims developer tooling that nothing in
#     the boot path calls. `aggressive` adds the core utilities -- ls, grep,
#     find, curl, wc, diff -- which save the most tokens and break the most
#     things. Opt in deliberately.
#   * A bypass. RTK_SHIM_DISABLED=1 in the environment turns every shim into a
#     direct exec of the real binary, with no rebuild.
#   * Recursion protection. rtk shells out to the very binaries being shimmed;
#     without RTK_SHIM_BYPASS the first `rtk git` would re-enter this wrapper
#     forever.
#   * Absolute fallback paths. Each shim records the real binary's path at build
#     time, so a shim can never resolve back to itself through PATH.
set -euo pipefail

LEVEL="${1:-safe}"

# /opt/hermes/bin, not a directory of our own: the upstream image already puts
# it first on PATH and it holds exactly one file (`hermes`), so dropping shims
# here needs no PATH manipulation at all. That matters because PATH would
# otherwise have to be re-declared at run time, where it is coupled to whatever
# the base image's PATH happens to be that week.
SHIM_DIR="${SHIM_DIR:-/opt/hermes/bin}"

# Commands with an rtk subcommand that nothing in the image's boot or supervision
# path invokes. Shimming these is close to free.
SAFE_COMMANDS=(
  git docker rg tree
  npm npx tsc prettier
  cargo go mvn sbt
  pytest ruff mypy
  gh glab kubectl psql
)

# High-value and high-blast-radius. Hermes lazy-installs Python packages through
# uv/pip at runtime, and its internals plus every shell script in the image use
# ls/grep/find/curl -- filtering their output is exactly the kind of change that
# fails somewhere unrelated and hard to trace.
AGGRESSIVE_COMMANDS=(
  ls grep find curl wget wc diff
  pip uv
)

case "$LEVEL" in
  safe)       commands=("${SAFE_COMMANDS[@]}") ;;
  aggressive) commands=("${SAFE_COMMANDS[@]}" "${AGGRESSIVE_COMMANDS[@]}") ;;
  none)
    echo "install-shims: level 'none', no shims generated"
    exit 0
    ;;
  *)
    echo "install-shims: unknown level '$LEVEL' (want: safe, aggressive, none)" >&2
    exit 1
    ;;
esac

install -d -m 0755 -o root -g root "$SHIM_DIR"

# Two phases on purpose. SHIM_DIR is itself on PATH -- that is the whole point
# of using /opt/hermes/bin -- so every target has to be resolved BEFORE the
# first shim is written. Interleaving the two would let a shim written earlier
# in the loop shadow the real binary for a later lookup, and each shim would
# end up pointing at another shim.
declare -A targets=()
skipped=()

for cmd in "${commands[@]}"; do
  # Only shim what is actually installed. The list is deliberately longer than
  # any one image needs so the same script works across base image versions.
  if ! real="$(command -v "$cmd" 2>/dev/null)"; then
    skipped+=("$cmd")
    continue
  fi
  real="$(readlink -f "$real")"

  # A target inside SHIM_DIR means a previous run already shimmed this command
  # and we are about to wrap a wrapper. Refuse rather than build a loop.
  case "$real" in
    "${SHIM_DIR}/"*)
      echo "install-shims: '$cmd' already resolves to a shim ($real); refusing to wrap it" >&2
      exit 1
      ;;
  esac

  targets["$cmd"]="$real"
done

created=0

for cmd in "${!targets[@]}"; do
  real="${targets[$cmd]}"

  cat >"${SHIM_DIR}/${cmd}" <<EOF
#!/bin/sh
# rtk shim for ${cmd} -- generated by scripts/install-shims.sh. Do not edit.
# Real binary: ${real}
#
# RTK_SHIM_DISABLED : operator kill switch, set it in compose.yaml.
# RTK_SHIM_BYPASS   : set by this shim before calling rtk, so that rtk's own
#                     invocation of ${cmd} lands on the real binary instead of
#                     recursing back into here.
if [ -n "\${RTK_SHIM_DISABLED:-}" ] || [ -n "\${RTK_SHIM_BYPASS:-}" ]; then
    exec "${real}" "\$@"
fi

# A missing or broken rtk must degrade to the plain command, never to an error:
# this wrapper sits in front of tooling the agent needs to keep working.
if ! command -v rtk >/dev/null 2>&1; then
    exec "${real}" "\$@"
fi

RTK_SHIM_BYPASS=1
export RTK_SHIM_BYPASS
exec rtk ${cmd} "\$@"
EOF

  chmod 0755 "${SHIM_DIR}/${cmd}"
  chown root:root "${SHIM_DIR}/${cmd}"
  created=$((created + 1))
done

echo "install-shims: level=${LEVEL} created=${created} dir=${SHIM_DIR}"
if [ ${#skipped[@]} -gt 0 ]; then
  echo "install-shims: not present in image, skipped: ${skipped[*]}"
fi
